const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const script=fs.readFileSync('static/js/dashboard.js','utf8');
const fn=script.slice(script.indexOf('function updateMotion('),script.indexOf('function flowState('));
let path='M107 205 H260',restarts=0,paused=true;
const motion={getAttribute:()=>path,setAttribute:(name,value)=>{path=value;},beginElement:()=>restarts++};
const particle={classList:{toggle:(name,value)=>{paused=value;}},querySelector:()=>motion};
const context={document:{querySelector:()=>particle}};vm.createContext(context);vm.runInContext(fn,context);
context.updateMotion('grid','M107 205 H260',true);
assert.equal(restarts,0);assert.equal(paused,false);
context.updateMotion('grid','M260 205 H107',true);
assert.equal(path,'M260 205 H107');assert.equal(restarts,1);
context.updateMotion('grid','M260 205 H107',true);assert.equal(restarts,1);
context.updateMotion('grid','M107 205 H260',true);assert.equal(restarts,2);
context.updateMotion('grid','M107 205 H260',false);assert.equal(paused,true);
context.updateMotion('battery','M300 230 V313',true);
context.updateMotion('battery','M300 313 V230',true);assert.equal(path,'M300 313 V230');
console.log('Motion direction changes, stable refresh and inactive state: OK');
